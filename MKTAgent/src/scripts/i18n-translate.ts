// Build-time catalog generator (i18n phase 04). Fills the MISSING keys of a non-English catalog from
// the English source, via the same Gemini plumbing the app already uses — NEVER at runtime (that would
// bill per pageview). Human edits are sacred: only absent keys are generated, existing values are never
// touched.
//
// Risk split (same tiering as the migration): ACT-ON keys (money/irreversible/connect) land in a
// separate `catalog.<locale>.review.ts` for human sign-off before promotion; low-risk chrome keys go
// straight into the main catalog. A mistranslated "Confirm" on a credit dialog is a money bug, so the
// pipeline is not the whole answer for those.
//
//   npx tsx src/scripts/i18n-translate.ts --locale id
//   npx tsx src/scripts/i18n-translate.ts --locale vi --dry   # report only, write nothing
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { readFile, writeFile } from 'node:fs/promises';
import { env } from '../config/env.ts';
import { callGeminiJson } from '../orchestration/master/llm-json.ts';
import { recordLlmUsage } from '../cost/llm-usage.ts';
import type { GeminiUsage } from '../orchestration/executor/node-cost.ts';

const REPO = new URL('../..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const I18N_DIR = join(REPO, 'web', 'src', 'i18n');
const LOCALES = new Set(['vi', 'id', 'ko']);
const BATCH = 40;

// A key is "act-on" (needs human review) when it belongs to a money/irreversible/connect area. Anything
// else is chrome and may ship generated. Kept broad on purpose — false-positive "needs review" is safe.
const ACT_ON = /^(approve\.|credits\.|connect\.|reconnect\.|confirm\.|schedule\.|publish\.|err\.|notice\.|autonomy\.grant|video\.approve|gate\.external|flow\.abort|plan\.tier)/;

const paramsOf = (s: string): Set<string> => new Set([...s.matchAll(/\{(\w+)\}/g)].map((m) => m[1]!));
const eqSet = (a: Set<string>, b: Set<string>): boolean => a.size === b.size && [...a].every((x) => b.has(x));
// A translated string lands in a .ts file — reject anything that could break out of the string literal.
const unsafe = (s: string): boolean => /[`]|\$\{|<\/script/i.test(s);

const load = async (name: string, member: string): Promise<Record<string, string>> =>
  (await import(pathToFileURL(join(I18N_DIR, name)).href))[member];

const langName = (l: string): string => ({ vi: 'Vietnamese', id: 'Indonesian', ko: 'Korean' } as Record<string, string>)[l] ?? l;

const translateBatch = async (locale: string, batch: Array<[string, string]>): Promise<Record<string, string>> => {
  const system =
    `You are a professional UI localizer. Translate app interface strings into ${langName(locale)}. ` +
    `Return ONLY a JSON object mapping each given key to its translation. Preserve every {token} EXACTLY ` +
    `(same names, do not translate or reorder them away from their sense). Keep it natural and concise for ` +
    `a software UI. Keep leading emoji/symbols. Do not add keys.`;
  const user = JSON.stringify(Object.fromEntries(batch.map(([k, v]) => [k, v])));
  let usage: GeminiUsage | null = null;
  const out = (await callGeminiJson(system, user, (u) => { usage = u; })) as Record<string, string>;
  if (usage) await recordLlmUsage({ ownerId: null, surface: 'i18n', model: env.GEMINI_MODEL, usage });
  return out;
};

const serialize = (locale: string, member: string, entries: Array<[string, string]>): string => {
  const body = entries
    .sort((a, b) => a[0].localeCompare(b[0]))
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join('\n');
  return (
    `// GENERATED by src/scripts/i18n-translate.ts — act-on keys awaiting human review. Promote a reviewed\n` +
    `// entry into catalog.${locale}.ts and delete it here. Do not hand-edit for long; regeneration overwrites.\n` +
    `import type { MessageKey } from './catalog.en';\n\n` +
    `export const ${member}: Partial<Record<MessageKey, string>> = {\n${body}\n};\n`
  );
};

const main = async (): Promise<void> => {
  const argv = process.argv.slice(2);
  const locale = argv[argv.indexOf('--locale') + 1];
  const dry = argv.includes('--dry');
  if (!locale || !LOCALES.has(locale)) { console.error(`usage: --locale <${[...LOCALES].join('|')}> [--dry]`); process.exit(2); }
  if (!env.GEMINI_API_KEY) { console.error('GEMINI_API_KEY not configured — this is a build-time generator, it needs a key.'); process.exit(2); }

  const en = await load('catalog.en.ts', 'en');
  const existing = await load(`catalog.${locale}.ts`, locale);
  const missing = Object.keys(en).filter((k) => !(k in existing));
  console.log(`i18n-translate ${locale}: ${Object.keys(en).length} en keys, ${Object.keys(existing).length} translated, ${missing.length} missing`);
  if (missing.length === 0) { console.log('nothing to generate.'); process.exit(0); }
  if (dry) { console.log('missing:', missing.join(', ')); process.exit(0); }

  const generated: Record<string, string> = {};
  for (let i = 0; i < missing.length; i += BATCH) {
    const batch = missing.slice(i, i + BATCH).map((k) => [k, en[k]!] as [string, string]);
    const out = await translateBatch(locale, batch);
    for (const [k, srcText] of batch) {
      const got = out[k];
      if (typeof got !== 'string' || !got.trim()) throw new Error(`missing translation for "${k}"`);
      if (unsafe(got)) throw new Error(`unsafe characters in translation for "${k}": ${got}`);
      if (!eqSet(paramsOf(srcText), paramsOf(got))) {
        throw new Error(`param mismatch for "${k}": en{${[...paramsOf(srcText)]}} vs ${locale}{${[...paramsOf(got)]}}`);
      }
      generated[k] = got;
    }
    console.log(`  batch ${i / BATCH + 1}: +${batch.length}`);
  }

  const review = Object.entries(generated).filter(([k]) => ACT_ON.test(k));
  const ship = Object.entries(generated).filter(([k]) => !ACT_ON.test(k));

  if (ship.length) {
    const merged = [...Object.entries(existing), ...ship] as Array<[string, string]>;
    await writeFile(join(I18N_DIR, `catalog.${locale}.ts`), serializeMain(locale, merged), 'utf8');
    console.log(`  wrote ${ship.length} chrome key(s) → catalog.${locale}.ts`);
  }
  if (review.length) {
    await writeFile(join(I18N_DIR, `catalog.${locale}.review.ts`), serialize(locale, `${locale}Review`, review), 'utf8');
    console.log(`  wrote ${review.length} act-on key(s) → catalog.${locale}.review.ts (needs human sign-off)`);
  }
  process.exit(0);
};

// The main catalog keeps the same header the hand-authored files use, so a generated chrome file reads
// like the rest. Deterministic key order → reviewable diffs.
const serializeMain = (locale: string, entries: Array<[string, string]>): string => {
  const body = entries
    .sort((a, b) => a[0].localeCompare(b[0]))
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join('\n');
  return (
    `// ${langName(locale)} catalog. Partial — missing keys fall back to English. Chrome keys may be\n` +
    `// generated (src/scripts/i18n-translate.ts); act-on keys are hand-reviewed. See catalog.vi.ts for the contract.\n` +
    `import type { MessageKey } from './catalog.en';\n\n` +
    `export const ${locale}: Partial<Record<MessageKey, string>> = {\n${body}\n};\n`
  );
};

main().catch((e) => { console.error('i18n-translate failed:', e instanceof Error ? e.message : e); process.exit(1); });
